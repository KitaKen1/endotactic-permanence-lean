#!/usr/bin/env python3
"""Adapt complete proofs to the independently written FC presentation."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
FC = ROOT / "FClikelean/EndotacticPermanence.lean"
OUTPUT = ROOT / "lean/EndotacticPublication/FCPresentation.lean"

BRIDGE = '''
/-- The same reactions in the proof-library representation. -/
def toProofNetwork {d m : ℕ} (N : Network d m) : Endotactic.Network d (Fin m) :=
  ⟨N.source, N.target⟩

/-- A proof-library network with finite reaction indices. -/
def fromProofNetwork {d m : ℕ} (N : Endotactic.Network d (Fin m)) : Network d m :=
  ⟨N.source, N.target⟩

theorem toProof_fromProof {d m : ℕ} (N : Endotactic.Network d (Fin m)) :
    toProofNetwork (fromProofNetwork N) = N := by
  cases N
  rfl

theorem fromProof_toProof {d m : ℕ} (N : Network d m) :
    fromProofNetwork (toProofNetwork N) = N := by
  cases N
  rfl

theorem Network.isEndotactic_iff {d m : ℕ} (N : Network d m) :
    N.IsEndotactic ↔ (toProofNetwork N).IsEndotactic := by
  rfl

theorem Network.permanentForRates_iff_compact {d m : ℕ} (N : Network d m)
    (hd : 0 < d) {k : Fin m → ℝ → ℝ} {c : Fin d → ℝ} (hc : Positive c) :
    N.PermanentForRates k c ↔ (toProofNetwork N).PermanentForRates k c := by
  change (toProofNetwork N).BoundedPermanentForRates k c ↔ _
  exact (toProofNetwork N).boundedPermanentForRates_iff hd hc

theorem Network.uniformPermanent_iff_compact {d m : ℕ} (N : Network d m)
    (hd : 0 < d) {ℓ u : ℝ} {c : Fin d → ℝ} (hc : Positive c) :
    N.UniformPermanent ℓ u c ↔ (toProofNetwork N).UniformPermanent ℓ u c (fun _ => True) := by
  change (toProofNetwork N).UniformBoundedPermanent ℓ u c ↔ _
  exact (toProofNetwork N).uniformBoundedPermanent_iff hd hc

'''

PROOFS = {
    "extended_permanence": '''  constructor
  · intro _ d m hd N hN ℓ u hℓ hlu k hk hr c hc
    apply (N.permanentForRates_iff_compact hd hc).mpr
    exact (EndotacticPublication.extended_permanence.mp True.intro)
      d m hd (toProofNetwork N) (N.isEndotactic_iff.mp hN) ℓ u hℓ hlu k hk hr c hc
  · intro _
    exact True.intro''',
    "measurable_extended_permanence": '''  constructor
  · intro _ d m hd N hN ℓ u hℓ hlu c hc
    apply (N.uniformPermanent_iff_compact hd hc).mpr
    exact (EndotacticPublication.measurable_extended_permanence.mp True.intro)
      d m hd (toProofNetwork N) (N.isEndotactic_iff.mp hN) ℓ u hℓ hlu c hc
  · intro _
    exact True.intro''',
}


def generate():
    text = FC.read_text()
    start = text.index("namespace Endotactic\n")
    first_theorem = text.index("theorem extended_permanence")
    first_doc = text.rfind("/--", start, first_theorem)
    definitions = text[start:first_doc].replace("namespace Endotactic\n", "namespace EndotacticFC\n", 1)
    targets = text[first_doc:]
    targets = re.sub(r"^@\[category[\s\S]*?\]\s*\n", "", targets, flags=re.M)
    targets = targets.replace("end Endotactic", "end EndotacticFC")
    for name, proof in PROOFS.items():
        pattern = r"(theorem " + re.escape(name) + r"\s*:[\s\S]*?:= by)\s*\n\s*sorry\b"
        targets, count = re.subn(pattern, lambda m: m.group(1) + "\n" + proof, targets, count=1)
        if count != 1:
            raise ValueError(f"Cannot adapt target: {name}")
    header = '''import EndotacticPublication.Main
import EndotacticPublication.CoordinateBounds
import Mathlib.Data.Matrix.Mul

/-!
# Complete proofs for the FC coordinate-bound presentation

The presentation definitions and target types come from the independently
written FC draft. Network conversion and compact/coordinate-bound equivalences
adapt the existing complete proofs. No proof-library interface is imposed on
the draft. Generated by lean/scripts/make_fc_proof.py.
-/

'''
    content = header + definitions + BRIDGE + targets
    for name in ["toProof_fromProof", "fromProof_toProof", "Network.isEndotactic_iff",
                 "Network.permanentForRates_iff_compact", "Network.uniformPermanent_iff_compact",
                 *PROOFS]:
        content += "\n#print axioms EndotacticFC." + name + "\n"
    metadata = {
        "generator": "lean/scripts/make_fc_proof.py",
        "fc_source_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "output": "lean/EndotacticPublication/FCPresentation.lean",
        "output_sha256": hashlib.sha256(content.encode()).hexdigest(),
        "target_namespace": "EndotacticFC",
        "presentation_definition_count": len(re.findall(r"^(?:def|structure)\s+", definitions, re.M)),
    }
    return content, metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content, metadata = generate()
    mapping = ROOT / "lean/evidence/fc_presentation_source_map.json"
    if args.check:
        if OUTPUT.read_text() != content or json.loads(mapping.read_text()) != metadata:
            raise ValueError("Stale complete proof for the FC presentation")
    else:
        OUTPUT.write_text(content)
        mapping.write_text(json.dumps(metadata, indent=2) + "\n")
    print("FC presentation proofs: 11 definitions + Network; compact equivalences and both targets")


if __name__ == "__main__":
    main()
